std::optional<Segments> App::pathSegments(const std::string& path) const {
    Segments raw;
    std::size_t at = 0;
    for (;;) {
        const auto cut = path.find('/', at);
        raw.push_back(path.substr(at, cut == std::string::npos ? std::string::npos : cut - at));
        if (cut == std::string::npos) break;
        at = cut + 1;
    }
    const auto checked = requestSegments(urlPathOf(raw));
    if (!checked || *checked != raw) return std::nullopt;
    return checked;
}

// One file dialog per window. The request is claimed when it arrives, before it waits in the window queue:
// a second dialog request (a double click, or a click queued while the first dialog is open) is refused
// at once instead of opening a second dialog after the first. The claim ends when the dialog has closed,
// confirmed or cancelled (endDialog).
bool App::claimDialog(const Json& m) {
    const std::string& type = m.at("type").str();
    if (!opensDialog(type)) return true;
    if (!dialogBusy_) {
        dialogBusy_ = true;
        return true;
    }
    refuseDialog(m);
    return false;
}

// The answer to a dialog request that is not carried out.
void App::refuseDialog(const Json& m) {
    const std::string& type = m.at("type").str();
    if (type == "openDialog") postOpenFailed(m.at("op").num());
    else if (type == "saveAs") post(Json::object().set("type", "saveCancelled").set("id", m.at("id").num()));
}

// A page counts as open from the moment the core hands it over, before the interface reports it: a logoff
// query in between must not find "no page". A report of "no page" counts only once the interface has
// handled the latest page handed over (`seen`), whether it opened it or not.
void App::postOpened(Json m) {
    pageOpen_ = true;
    post(m.set("seq", ++delivered_));
}

void App::noteUnsaved(const Json& m) {
    unsaved_ = m.at("value").boolean();
    const bool open = m.at("open").boolean();
    if (m.at("seen").num() >= delivered_) pageOpen_ = open;
    else if (open) pageOpen_ = true;
    if (!unsaved_ && endBlocked_) endBlocked_ = !ShutdownBlockReasonDestroy(window_);
}

void App::endDialog() {
    dialogBusy_ = false;
    post(Json::object().set("type", "dialogDone"));
}

void App::onUiMessage(const Json& m) {
    const std::string& type = m.at("type").str();
    // A dialog request ends its claim when this handler returns, whichever way it returns.
    AtExit dialogDone{opensDialog(type) ? std::function<void()>([this] { endDialog(); }) : std::function<void()>()};
    if (type == "openDialog" || type == "openFile" || type == "newPage") openOp_ = m.at("op").num();
    if (type == "ready") {
        if (uiReady_) return;
        uiReady_ = true;
        post(Json::object().set("type", "init").set("version", HSE_VERSION));
        if (!startFile_.empty()) {
            const std::wstring file = startFile_;
            startFile_.clear();
            setProject(parentOf(file), true, [this, file]() {
                if (const auto segs = segmentsBelow(root_, file)) openFile(*segs, 0);
            });
            return;
        }
        const std::wstring last = readSetting(L"LastProject");
        if (last.empty()) return;
        const UINT64 generation = projectGen_;
        if (!fileWorkers_.submit([this, last, generation]() {
            const bool there = isFolder(last);  // may wait for a network drive
            runLater([this, last, there, generation]() {
                if (generation != projectGen_) return;
                if (there) setProject(last, false);
                else if (!there) postStatus("Der letzte Projektordner ist gerade nicht erreichbar. Öffne ihn neu.", true);
            });
        })) postStatus(kWorkersBusy, true);
    } else if (type == "layout") {
        pvVisible_ = m.at("visible").boolean();
        const int x = static_cast<int>(m.at("x").num()), y = static_cast<int>(m.at("y").num());
        const int w = static_cast<int>(m.at("w").num()), h = static_cast<int>(m.at("h").num());
        pvRect_ = {x, y, x + w, y + h};
        if (previewHost_) {
            SetWindowPos(previewHost_, HWND_TOP, x, y, w, h, SWP_NOACTIVATE | (pvVisible_ && w > 0 && h > 0 ? SWP_SHOWWINDOW : SWP_HIDEWINDOW));
        }
        if (pvController_) {
            pvController_->put_Bounds({0, 0, w, h});
            pvController_->put_IsVisible(pvVisible_ && !pvSegs_.empty());
        }
    } else if (type == "preview") {
        if (const auto segs = pathSegments(m.at("path").str())) showPreview(*segs, m.at("text").str());
    } else if (type == "openProject") {
        if (const auto folder = pickFolder(window_, root_)) setProject(*folder, true);
    // Opening, a new page and pictures carry an operation number `op` that every answer repeats, so the
    // interface takes only the answer to its latest request (see docs/ARCHITECTURE.md, "Messages").
    } else if (type == "openDialog") {
        const double op = m.at("op").num();
        const auto file = pickPageFile(window_, root_);
        if (!file) { postOpenFailed(op); return; }
        const std::wstring f = *file;
        const auto bound = boundary_;
        const UINT64 gen = projectGen_;
        if (!fileWorkers_.submit([this, f, bound, gen, op]() {
            auto segs = projectSegmentsOf(bound, f);
            runLater([this, f, gen, op, segs = std::move(segs)]() {
                // Another project folder or another page was asked for meanwhile: this late choice must not
                // switch the project folder, which would close the page open now with what was typed in it.
                if (gen != projectGen_ || op != openOp_) { postOpenFailed(op); return; }
                if (segs) { openFile(*segs, op); return; }
                setProject(parentOf(f), true, [this, f, op]() {
                    if (const auto s = segmentsBelow(root_, f)) openFile(*s, op);
                    else postOpenFailed(op);
                });
            });
        })) postOpenFailed(op, "Die Seite kann gerade nicht geöffnet werden", kWorkersBusy);
    } else if (type == "openFile") {
        const double op = m.at("op").num();
        if (const auto segs = pathSegments(m.at("path").str())) openFile(*segs, op);
        else postOpenFailed(op, "Die Seite kann nicht geöffnet werden", "Der Dateiname ist ungültig.");
    } else if (type == "newPage") {
        const double op = m.at("op").num();
        if (const auto segs = pathSegments(m.at("path").str())) newPage(*segs, m.at("text").str(), op);
        else postOpenFailed(op, "Die Seite konnte nicht angelegt werden", "Der Dateiname ist ungültig.");
    } else if (type == "save") {
        // Every answer to a save carries the id of its request, so the interface never takes the answer
        // to an older save for the page open now. `base` is the fingerprint of the file as the open page
        // was read or last saved.
        const double id = m.at("id").num();
        const auto base = parseFingerprint(m.at("base").str());
        if (const auto segs = pathSegments(m.at("path").str())) save(*segs, m.at("text").str(), base, id);
        else post(failedAnswer("Der Dateiname ist ungültig.").set("id", id));
    } else if (type == "saveAs") {
        const auto segs = pathSegments(m.at("path").str());
        saveAs(segs ? *segs : Segments{}, m.at("text").str(), parseFingerprint(m.at("base").str()), m.at("createOnly").boolean(), m.at("id").num());
    } else if (type == "pickPicture") {
        if (const auto segs = pathSegments(m.at("page").str())) pickPicture(*segs, m.at("op").num());
    } else if (type == "copyPicture") {
        if (const auto segs = pathSegments(m.at("page").str())) copyPicture(m.at("token").str(), *segs, m.at("op").num());
    } else if (type == "viewInBrowser") {
        if (const auto segs = pathSegments(m.at("path").str())) viewInBrowser(*segs);
    } else if (type == "rescue") {
        const double id = m.at("id").num();
        if (const auto segs = pathSegments(m.at("path").str())) rescue(*segs, m.at("text").str(), id);
        else post(Json::object().set("type", "rescueFailed").set("id", id).set("message", "Der Dateiname ist ungültig."));
    } else if (type == "closeOk") {
        DestroyWindow(window_);
    }
}

