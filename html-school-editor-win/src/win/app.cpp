void App::setProject(const std::wstring& root, bool remember, std::function<void()> then) {
    std::wstring r = root;
    while (r.size() > 3 && (r.back() == L'\\' || r.back() == L'/')) r.pop_back();
    root_ = r;
    boundary_ = std::make_shared<ProjectBoundary>(root_);  // resolved on the workers (junctions followed)
    ++projectGen_;  // answers of work started for the previous folder are not used any more
    KillTimer(window_, TIMER_SCAN);
    scanPending_ = false;
    pictureTokens_.clear();
    pvSegs_.clear();
    pvText_.reset();
    pvReloadAgain_ = false;
    resetPreviewLoad();
    if (pvController_) pvController_->put_IsVisible(FALSE);
    if (remember) writeSetting(L"LastProject", root_);
    // The interface closes the open page of the previous project now, before anything of the new one arrives.
    post(Json::object().set("type", "projectChanged").set("name", toUtf8(lastComponent(root_))));
    watcher_.start(root_, window_, WM_APP_FILES, static_cast<WPARAM>(projectGen_));
    rescan("Projektordner: " + toUtf8(lastComponent(root_)));
    if (then) then();
}

void App::rescan(const std::string& message) {
    if (root_.empty()) return;
    lastScan_ = GetTickCount64();
    const std::wstring root = root_;
    const UINT64 project = projectGen_, scan = ++scanGen_;
    if (!fileWorkers_.submit([this, root, message, project, scan]() {
        const bool there = isFolder(root);
        auto entries = there ? scanProject(root) : std::vector<ProjectEntry>{};
        runLater([this, root, there, message, project, scan, entries = std::move(entries)]() {
            if (project != projectGen_ || scan != scanGen_) return;
            if (!there) {
                postStatus("Der Projektordner ist gerade nicht erreichbar. Ist die Verbindung zum Netzlaufwerk unterbrochen?", true);
                return;
            }
            Json files = Json::array();
            for (const auto& e : entries) {
                const char* kind = e.kind == FileKind::Page ? "page" : e.kind == FileKind::Style ? "style" : "picture";
                files.push(Json::object().set("path", joinSegments(e.segs)).set("kind", kind));
            }
            Json m = Json::object().set("type", "project").set("name", toUtf8(lastComponent(root))).set("files", std::move(files));
            if (!message.empty()) m.set("message", message);
            post(m);
        });
    })) postStatus(kWorkersBusy, true);
}

void App::openFile(const Segments& segs, double op) {
    if (root_.empty()) { postOpenFailed(op); return; }
    const std::wstring path = joinPath(root_, segs);
    const UINT64 gen = projectGen_;
    const auto bound = boundary_;
    postStatus("Wird geöffnet …");
    if (!fileWorkers_.submit([this, path, segs, gen, op, bound]() {
        const std::wstring rootFinal = rootOf(bound);  // on the worker: may wait for a network drive
        ReadResult r = readFileBytes(path, kMaxPageBytes, rootFinal);
        runLater([this, segs, gen, op, r = std::move(r)]() {
            if (gen != projectGen_) { postOpenFailed(op); return; }  // another project folder was opened meanwhile
            if (r.error != ERROR_SUCCESS) {
                postStatus("");
                postOpenFailed(op, "Die Seite kann nicht geöffnet werden", errorText(r.error));
                return;
            }
            postOpened(Json::object().set("type", "opened").set("op", op).set("path", joinSegments(segs)).set("name", segs.back())
                           .set("base", fingerprintText(fingerprintOf(r.bytes))).set("data", base64Encode(r.bytes)));
        });
    })) postOpenFailed(op, "Die Seite kann gerade nicht geöffnet werden", kWorkersBusy);
}

void App::save(const Segments& segs, std::string bytes, std::optional<Fingerprint> base, double id) {
    if (busy_) {
        post(failedAnswer("Es wird gerade noch gespeichert.").set("id", id));
        return;
    }
    if (bytes.size() > kMaxPageBytes) {
        post(failedAnswer("Die Seite ist größer als 5 MB. So große Seiten kann der Editor nicht wieder öffnen.").set("id", id));
        return;
    }
    busy_ = true;
    const std::wstring path = joinPath(root_, segs);
    const auto bound = boundary_;
    if (!fileWorkers_.submit([this, path, base, id, bound, bytes = std::move(bytes)]() {
        const std::wstring rootFinal = rootOf(bound);  // on the worker: may wait for a network drive
        Json answer = writeChecked(path, bytes, base, rootFinal);
#ifdef HSE_TEST_HOOKS
        // Test build only: holds the answer back, so the acceptance tests can type while a save is on its way.
        wchar_t delay[16];
        if (GetEnvironmentVariableW(L"HSE_TEST_SAVE_DELAY_MS", delay, 16)) Sleep(static_cast<DWORD>(_wtoi(delay)));
#endif
        runLater([this, id, answer = std::move(answer)]() mutable {
            busy_ = false;
            post(answer.set("id", id));
        });
    }, true)) {
        busy_ = false;
        post(failedAnswer(kWorkersBusy).set("id", id));
    }
}

void App::saveAs(const Segments& current, std::string bytes, std::optional<Fingerprint> base, bool createOnly, double id) {
    if (busy_) {
        post(failedAnswer("Es wird gerade noch gespeichert.").set("id", id));
        return;
    }
    if (bytes.size() > kMaxPageBytes) {
        post(failedAnswer("Die Seite ist größer als 5 MB. So große Seiten kann der Editor nicht wieder öffnen.").set("id", id));
        return;
    }
    std::wstring start = root_;
    std::wstring name = L"seite.html";
    if (!current.empty()) {
        start = parentOf(joinPath(root_, current));
        name = toWide(current.back());
    }
    // A new name only (the way out of a conflict): no overwrite question, an existing file is refused.
    const auto file = pickSaveFile(window_, start, name, !createOnly);
    if (!file) {
        post(Json::object().set("type", "saveCancelled").set("id", id));
        return;
    }
    const auto segs = segmentsBelow(root_, *file);
    const auto checked = segs ? requestSegments(urlPathOf(*segs)) : std::nullopt;
    if (!checked || kindOf(checked->back()) != FileKind::Page) {
        post(Json::object().set("type", "saveCancelled").set("id", id));
        postError("Bitte im Projektordner speichern", segs ? "Der Name ist nicht möglich. Verwende Buchstaben, Ziffern, „-“ und „_“ und die Endung .html."
                                                           : "Speichere die Seite in deinem Projektordner, damit Bilder und Links stimmen.");
        return;
    }
    const std::wstring path = joinPath(root_, *checked);
    // The open page under its own name: the same check as an ordinary save.
    const bool samePage = !current.empty() && lower(path) == lower(joinPath(root_, current));
    busy_ = true;
    const auto bound = boundary_;
    if (!fileWorkers_.submit([this, path, id, base, createOnly, samePage, bound, segs = *checked, bytes = std::move(bytes)]() {
        const std::wstring rootFinal = rootOf(bound);  // on the worker: may wait for a network drive
        Json answer;
        if (createOnly || !isFile(path)) answer = writeNew(path, bytes, rootFinal);
        else if (samePage) answer = writeChecked(path, bytes, base, rootFinal);
        else if (const DWORD e = checkParentWithin(path, rootFinal); e != ERROR_SUCCESS) answer = failedAnswer(errorText(e));
        else {
            // Another existing page: the pupil has just confirmed in the dialog that it is replaced. A file
            // that leads out of the project (a link) is not replaced.
            CheckedFile target;
            const DWORD t = target.open(path, rootFinal);
            if (t == ERROR_OUTSIDE_PROJECT) {
                answer = failedAnswer(errorText(t));
            } else {
                const WriteResult w = replaceFileAtomic(path, bytes);
                const Fingerprint mine = fingerprintOf(bytes);
                answer = w.error == ERROR_SUCCESS ? savedAnswer(mine)
                       : w.error == ERROR_FILE_NOT_FOUND && w.keptOld.empty() ? writeNew(path, bytes, rootFinal)  // removed meanwhile
                       : afterFailedWrite(path, w, mine, std::nullopt, rootFinal);
            }
        }
        if (answer.at("type").str() == "saved") answer.set("path", joinSegments(segs)).set("name", segs.back());
        runLater([this, id, answer = std::move(answer)]() mutable {
            busy_ = false;
            const bool ok = answer.at("type").str() == "saved";
            post(answer.set("id", id));
            if (ok) rescan();
        });
    }, true)) {
        busy_ = false;
        post(failedAnswer(kWorkersBusy).set("id", id));
    }
}

void App::newPage(const Segments& segs, std::string bytes, double op) {
    if (root_.empty() || kindOf(segs.back()) != FileKind::Page) { postOpenFailed(op); return; }
    const std::wstring path = joinPath(root_, segs);
    const UINT64 gen = projectGen_;
    const auto bound = boundary_;
    if (!fileWorkers_.submit([this, path, segs, gen, op, bound, bytes = std::move(bytes)]() {
        const std::wstring rootFinal = rootOf(bound);  // on the worker: may wait for a network drive
        DWORD e = createFoldersWithin(parentOf(path), rootFinal);
        if (e == ERROR_SUCCESS) e = checkParentWithin(path, rootFinal);
        if (e == ERROR_SUCCESS) e = createFileAtomic(path, bytes).error;
        runLater([this, segs, gen, op, bytes, e]() {
            if (gen != projectGen_) { postOpenFailed(op); return; }
            if (e != ERROR_SUCCESS) {
                postOpenFailed(op, "Die Seite konnte nicht angelegt werden", errorText(e));
                return;
            }
            postOpened(Json::object().set("type", "opened").set("op", op).set("path", joinSegments(segs)).set("name", segs.back())
                           .set("base", fingerprintText(fingerprintOf(bytes))).set("data", base64Encode(bytes)));
            rescan("Neue Seite angelegt: " + joinSegments(segs));
        });
    }, true)) postOpenFailed(op, "Die Seite konnte nicht angelegt werden", kWorkersBusy);
}

void App::pickPicture(const Segments& page, double op) {
    if (root_.empty()) return;
    // The dialog starts in "bilder" if it exists, else in the project folder (the dialog itself checks).
    const auto file = pickPictureFile(window_, root_ + L"\\bilder", root_);
    if (!file) return;
    const std::string name = toUtf8(lastComponent(*file));
    if (kindOf(name) != FileKind::Picture) postStatus("„" + name + "“ ist vielleicht kein Bildformat, das Browser anzeigen. Gut sind .jpg, .png, .gif, .webp und .svg.", true);
    const std::wstring f = *file;
    const auto bound = boundary_;
    const UINT64 gen = projectGen_;
    if (!fileWorkers_.submit([this, f, name, bound, gen, page, op]() {
        auto segs = projectSegmentsOf(bound, f);
        runLater([this, f, name, gen, page, op, segs = std::move(segs)]() {
            if (gen != projectGen_) return;
            if (segs) {
                post(Json::object().set("type", "picture").set("op", op).set("src", relativeAddress(page, *segs)));
                return;
            }
            const std::string token = randomToken();
            pictureTokens_[token] = f;
            post(Json::object().set("type", "pictureOutside").set("op", op).set("name", name).set("token", token));
        });
    })) postStatus(kWorkersBusy, true);
}

void App::copyPicture(const std::string& token, const Segments& page, double op) {
    const auto it = pictureTokens_.find(token);
    if (it == pictureTokens_.end() || root_.empty()) return;
    const std::wstring source = it->second;
    pictureTokens_.erase(it);
    const std::wstring folder = root_ + L"\\bilder";
    const UINT64 gen = projectGen_;
    const auto bound = boundary_;
    if (!fileWorkers_.submit([this, source, folder, page, gen, op, bound]() {
        const std::wstring rootFinal = rootOf(bound);  // on the worker: may wait for a network drive
        DWORD e = createFoldersWithin(folder, rootFinal);
        std::string name;
        if (e == ERROR_SUCCESS) {
            std::vector<std::string> existing;
            WIN32_FIND_DATAW fd;
            const HANDLE h = FindFirstFileExW((folder + L"\\*").c_str(), FindExInfoBasic, &fd, FindExSearchNameMatch, nullptr, 0);
            if (h != INVALID_HANDLE_VALUE) {
                do existing.push_back(toUtf8(fd.cFileName));
                while (FindNextFileW(h, &fd));
                FindClose(h);
            }
            name = uniqueName(toUtf8(lastComponent(source)), existing);
            if (!CopyFileW(source.c_str(), (folder + L"\\" + toWide(name)).c_str(), TRUE)) e = GetLastError();
        }
        runLater([this, page, name, gen, op, e]() {
            if (gen != projectGen_) return;
            if (e != ERROR_SUCCESS) {
                postError("Das Bild konnte nicht kopiert werden", errorText(e));
                return;
            }
            post(Json::object().set("type", "picture").set("op", op).set("src", relativeAddress(page, {"bilder", name})));
            rescan("Bild kopiert nach bilder/" + name);
        });
    }, true)) postError("Das Bild konnte nicht kopiert werden", kWorkersBusy);
}

// A rescue copy of the text in the editor while a save hangs (for example on a network drive that does not
// answer). It goes to the local disk, %LOCALAPPDATA%\HtmlSchoolEditor\Rettungskopien, under a new name with
// the date and time, on its own worker: neither the project folder nor the file workers are touched, and
// the save that hangs goes on as before. `bytes` are the file bytes as a save would write them (BOM and
// every line break as in the editor).
void App::rescue(const Segments& page, std::string bytes, double id) {
    if (bytes.size() > kMaxPageBytes) {
        post(Json::object().set("type", "rescueFailed").set("id", id).set("message", "Die Seite ist größer als 5 MB."));
        return;
    }
    std::wstring stem = toWide(page.back()), extension = L".html";
    if (const auto dot = stem.rfind(L'.'); dot != std::wstring::npos && dot > 0) {
        extension = stem.substr(dot);
        stem.resize(dot);
    }
    // The name gains date and time; keep it well inside the path limit, without cutting a character in two.
    if (stem.size() > 60) stem.resize(IS_HIGH_SURROGATE(stem[59]) ? 59 : 60);
    if (extension.size() > 8) extension = L".html";
    const std::string pagePath = joinSegments(page);
    if (!rescueWorkers_.submit([this, stem, extension, id, pagePath, bytes = std::move(bytes)]() {
        // Only the local profile: no fallback to the temporary folder, which may be shared or redirected.
        const auto profile = profileDataFolder(L"Rettungskopien");
        if (!profile) {
            runLater([this, id, pagePath]() {
                post(Json::object().set("type", "rescueFailed").set("id", id).set("page", pagePath)
                         .set("message", "Auf diesem Computer kann gerade keine Rettungskopie angelegt werden."));
            });
            return;
        }
        const std::wstring folder = *profile;
        SYSTEMTIME t;
        GetLocalTime(&t);
        wchar_t stamp[32];
        swprintf_s(stamp, L"%04u-%02u-%02u_%02u-%02u-%02u", t.wYear, t.wMonth, t.wDay, t.wHour, t.wMinute, t.wSecond);
        std::wstring path;
        WriteResult w;
        for (int i = 1; i <= 50; ++i) {
            path = folder + L"\\" + stem + L"_" + stamp + (i > 1 ? L"_" + std::to_wstring(i) : std::wstring()) + extension;
            w = createFileAtomic(path, bytes);
            if (w.error != ERROR_FILE_EXISTS) break;
        }
        Json answer = w.error == ERROR_SUCCESS ? Json::object().set("type", "rescued").set("path", toUtf8(path))
                                               : Json::object().set("type", "rescueFailed").set("message", errorText(w.error));
        answer.set("page", pagePath);
        runLater([this, id, answer = std::move(answer)]() mutable { post(answer.set("id", id)); });
    }, true)) {
        post(Json::object().set("type", "rescueFailed").set("id", id).set("message", kWorkersBusy));
    }
}

void App::viewInBrowser(const Segments& segs) {
    if (root_.empty()) {
        postError("Der Browser wurde nicht geöffnet", errorText(ERROR_PATH_NOT_FOUND));
        return;
    }
    const std::wstring path = joinPath(root_, segs);
    const auto bound = boundary_;
    const UINT64 gen = projectGen_;
    // The check runs on a worker; an unreachable project folder refuses (no unchecked open).
    if (!fileWorkers_.submit([this, path, bound, gen]() {
        DWORD e = ERROR_PATH_NOT_FOUND;
        if (const std::wstring rootFinal = rootOf(bound); !rootFinal.empty()) {
            CheckedFile f;
            e = f.open(path, rootFinal);
        }
        runLater([this, path, gen, e]() {
            if (gen != projectGen_) return;
            if (e != ERROR_SUCCESS) {
                postError("Der Browser wurde nicht geöffnet", errorText(e));
                return;
            }
            const auto r = reinterpret_cast<INT_PTR>(ShellExecuteW(window_, L"open", path.c_str(), nullptr, nullptr, SW_SHOWNORMAL));
            if (r <= 32) postError("Der Browser konnte nicht geöffnet werden", "Öffne die Datei im Explorer mit einem Doppelklick.");
        });
    })) postError("Der Browser wurde nicht geöffnet", kWorkersBusy);
}

