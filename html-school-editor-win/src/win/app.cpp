struct CacheEntry {
    ULONGLONG size = 0;
    FILETIME time{};
    std::shared_ptr<const std::string> bytes;
    std::string actual;  // the path with the spelling on disk, if it differs from the request
};

struct FileCache {
    std::mutex lock;
    std::map<std::wstring, CacheEntry> entries;
    std::size_t total = 0;

    std::optional<CacheEntry> find(const std::wstring& key, ULONGLONG size, FILETIME time) {
        std::lock_guard g(lock);
        const auto it = entries.find(key);
        if (it == entries.end() || it->second.size != size || CompareFileTime(&it->second.time, &time) != 0) return std::nullopt;
        return it->second;
    }
    void put(const std::wstring& key, CacheEntry e) {
        std::lock_guard g(lock);
        if (total + e.bytes->size() > kCacheBytes) {
            entries.clear();
            total = 0;
        }
        const auto it = entries.find(key);
        if (it != entries.end()) total -= it->second.bytes->size();
        total += e.bytes->size();
        entries[key] = std::move(e);
    }
    void clear() {
        std::lock_guard g(lock);
        entries.clear();
        total = 0;
    }
};
FileCache gCache;

// Spelling of every segment on disk; empty if it equals the request exactly.
std::string actualSpelling(const std::wstring& root, const Segments& segs) {
    Segments actual;
    bool differs = false;
    std::wstring at = root;
    for (const auto& s : segs) {
        at = joinPath(at, {s});
        const auto name = actualName(at);
        const std::string got = name ? toUtf8(*name) : s;
        if (got != s) differs = true;
        actual.push_back(got);
    }
    return differs ? joinSegments(actual) : std::string();
}

